"""Exercise the actual Compose config with local TLS and fixture credentials.

Build first: docker build -t litecom:qa .
No signup, model calls, SMS, email, or Slack delivery is performed.
"""
import argparse
import io
import json
import os
from pathlib import Path
import ssl
import subprocess
import tarfile
import tempfile
import time
import urllib.error
import urllib.request
import uuid

parser = argparse.ArgumentParser()
parser.add_argument('--context')
parser.add_argument('--image', default='litecom:qa')
args = parser.parse_args()
docker = ['docker'] + (['--context', args.context] if args.context else [])
repo = Path(__file__).resolve().parents[1]
env = dict(os.environ, LITECOM_HOST='localhost', ACME_EMAIL='qa@example.com',
           TWILIO_ACCOUNT_SID='ACfixture', TWILIO_AUTH_TOKEN='fixture',
           TWILIO_MESSAGING_SERVICE_SID='MGfixture',
           SMTP_HOST='', SMTP_FROM='', SMTP_PORT='465', SMTP_USERNAME='',
           SMTP_PASSWORD='', SLACK_CLIENT_ID='', SLACK_CLIENT_SECRET='',
           LITECOM_DATA_DIR='/data/relay')

def run(command, **kwargs):
    return subprocess.run(command, check=True, cwd=repo, env=env, **kwargs)

config = json.loads(run(docker + ['compose', '--env-file', '.env.example',
                                 'config', '--format', 'json'],
                        capture_output=True, text=True).stdout)
config['name'] = 'litecom-qa-' + uuid.uuid4().hex[:10]
relay = config['services']['relay']
relay.pop('build', None)
relay['image'] = args.image
config['services']['https']['ports'] = [
    {'target': 443, 'published': '0', 'host_ip': '127.0.0.1', 'protocol': 'tcp'}]
# Explicit names generated by `compose config` must also be unique to this run.
for kind in ['volumes', 'networks']:
    for name, value in config.get(kind, {}).items():
        value['name'] = config['name'] + '_' + name

with tempfile.TemporaryDirectory(prefix='litecom-container-qa-') as temp:
    root = Path(temp)
    compose_file = root/'compose.json'
    compose_file.write_text(json.dumps(config))
    compose = docker + ['compose', '-f', str(compose_file)]
    try:
        run(compose + ['up', '-d', '--wait', '--wait-timeout', '90'])
        container = run(compose + ['ps', '-q', 'relay'], capture_output=True, text=True).stdout.strip()
        uid = run(compose + ['exec', '-T', 'relay', 'id', '-u'], capture_output=True, text=True).stdout.strip()
        assert uid == '65532', uid
        notices = run(compose + ['exec', '-T', 'relay', 'cat',
                                '/usr/share/doc/litecom/THIRD-PARTY-NOTICES.html'], capture_output=True).stdout
        assert notices == (repo/'THIRD-PARTY-NOTICES.html').read_bytes(), 'Container notices are stale or incomplete'
        details = json.loads(run(docker + ['inspect', container], capture_output=True, text=True).stdout)[0]
        assert details['HostConfig']['ReadonlyRootfs']
        assert not details['HostConfig'].get('PortBindings'), 'Relay port must stay internal'
        status = json.loads(run(compose + ['exec', '-T', 'relay', 'curl', '-fsS',
                                          'http://127.0.0.1:4141/api/capabilities'],
                                capture_output=True, text=True).stdout)
        assert status['phone'] and not status['development']
        cert = root/'root.crt'
        for attempt in range(30):
            ready = subprocess.run(compose + ['exec', '-T', 'https', 'test', '-f', '/data/caddy/pki/authorities/local/root.crt'], cwd=repo, env=env, capture_output=True)
            if ready.returncode == 0:
                break
            time.sleep(1)
        else:
            raise AssertionError('Caddy did not create its local test certificate')
        run(compose + ['cp', 'https:/data/caddy/pki/authorities/local/root.crt', str(cert)])

        def check_https():
            address = run(compose + ['port', 'https', '443'], capture_output=True, text=True).stdout.strip()
            port = address.rsplit(':', 1)[1]
            tls = ssl.create_default_context(cafile=cert)
            for attempt in range(20):
                try:
                    with urllib.request.urlopen(f'https://localhost:{port}/health', context=tls, timeout=2) as response:
                        assert json.load(response)['status'] == 'ok'
                    break
                except urllib.error.URLError:
                    if attempt == 19:
                        raise
                    time.sleep(.5)
            with urllib.request.urlopen(f'https://localhost:{port}/', context=tls, timeout=10) as response:
                assert 'Litecom' in response.read().decode()

        check_https()
        run(compose + ['exec', '-T', 'relay', 'litecom', 'backup', '--data', '/data/relay', '--output', '/data/backup-1'])
        run(compose + ['exec', '-T', 'relay', 'litecom', 'verify-backup', '/data/backup-1'])
        backups = root/'backups'
        backups.mkdir(mode=0o700)
        run(compose + ['cp', 'relay:/data/backup-1', str(backups)])
        run(compose + ['stop'])
        code = run(docker + ['inspect', '--format', '{{.State.ExitCode}}', container], capture_output=True, text=True).stdout.strip()
        assert code == '0', f'Relay did not stop gracefully: {code}'
        archive = io.BytesIO()
        with tarfile.open(fileobj=archive, mode='w') as tar:
            for name in ['manifest.json', 'litecom.db', 'storage.key']:
                tar.add(backups/'backup-1'/name, arcname=name, recursive=False)
        run(compose + ['run', '--rm', '--no-deps', '-T', '--entrypoint', 'sh', 'relay', '-c',
                       'mkdir /data/restore-input-1 && tar --no-same-owner -xf - -C /data/restore-input-1 && litecom restore /data/restore-input-1 --data /data/recovered-1'], input=archive.getvalue())
        assert relay['command'][-1] == '/data/relay'
        relay['command'][-1] = '/data/recovered-1'
        compose_file.write_text(json.dumps(config))
        run(compose + ['up', '-d', '--wait', '--wait-timeout', '90'])
        check_https()
        run(compose + ['exec', '-T', 'relay', 'litecom', 'backup', '--data', '/data/recovered-1', '--output', '/data/backup-2'])
        print('PASS: non-root container, current third-party notices, private relay port, trusted local HTTPS, live snapshot, graceful SIGTERM, documented restore import, recovered server restart.')
    finally:
        run(compose + ['down', '--volumes', '--remove-orphans'])
